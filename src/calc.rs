// ============================================================
// calc.rs —— 纯函数计算模块（1RM 估算公式）
// ============================================================
// 【教学说明】
// 这个文件是 M5 的第一个新文件，也是最简单的一个——它**不碰数据库、
// 不碰 HTTP、不碰 IO**，只有两个"输入数字 → 输出数字"的纯函数。
//
// 一、什么是纯函数，为什么重要？
//   纯函数 = 相同输入永远得到相同输出 + 无副作用（不读不写外界状态）。
//   - 今天算 epley_1rm(60.0, 8) 是 76.0，明天算还是 76.0，在火星上算也是 76.0
//   - 它不查数据库、不发网络请求、不改任何全局变量
//   好处：
//   1. 好测试：不需要搭数据库/服务器，直接 assert 数字
//   2. 好复用：M5 的网页能用，以后的 iced GUI 客户端也能用
//      （还记得上次讨论的"Cargo workspace 共享 calc.rs"吗？这就是伏笔）
//   3. 好推理：看签名 (f64, i64) -> f64 就知道它干什么，
//      不担心它偷偷动了什么状态
//
// 二、1RM 是什么？
//   1RM（One Rep Max）= 某动作理论上最多能举起一次的重量。
//   你不会每天去测 1RM（危险且影响训练），所以用公式从
//   "日常记录的实际重量 × 次数"反推。
//
// 三、两个公式
//   - Epley（从记录估 1RM）：
//       1RM = W × (1 + reps / 30)
//     例：60kg 做了 8 次 → 60 × (1 + 8/30) = 76.0kg
//     直觉："同样的重量能做更多次 = 更强"，次数越多估出的 1RM 越高。
//   - Wathan（从 1RM 反推目标次数下的重量 MRM）：
//       MRM = 1RM / (1.67 − 0.067 × target_reps)
//     例：1RM 100kg，想算 2 次能举多重 → 100 / (1.67 − 0.134) ≈ 65.1kg
//     页面展示 1RM / 2RM / 3RM 就是用 target_reps = 1 / 2 / 3。
//
// 📌 阶段要求：M5 你来实现这两个函数 + 单元测试。
//   实现完成后对照检查（完整实现备份在 docs/learning_path/M5_ref/）。
// ============================================================

// ============================================================
// 【教学：函数签名怎么读】
// ============================================================
// pub fn epley_1rm(weight: f64, reps: i64) -> f64
//   pub   → 公开（其他模块能用 calc::epley_1rm）
//   fn    → 函数
//   weight: f64  → 实际重量（kg），f64 因为可能有小数（35.5kg）
//   reps: i64    → 次数，整数
//   -> f64       → 返回估算的 1RM（kg）
//
// 【教学：边界条件 —— 防御性编程】
// weight <= 0 或 reps <= 0 说明这是条无效记录（没练/数据没填），
// 不能算 1RM（否则会算出 0 甚至负数，画图时污染趋势线）。
// 约定：无效输入 → 返回 0（页面遇到 0 就知道"这条不算"）。
// ============================================================

/// Epley 公式：从"实际重量 × 次数"估算 1RM
///
/// 公式：`1RM = W × (1 + reps / 30)`
///
/// 【教学：实现提示】
/// 1. 先判断边界：weight <= 0.0 或 reps <= 0 → return 0.0
/// 2. 注意类型转换：reps 是 i64，要用 `as f64` 转成浮点再除
/// 3. 计算：weight * (1.0 + reps as f64 / 30.0)
pub fn epley_1rm(weight: f64, reps: i64) -> f64
{
    (if weight <= 0.0
    {
        return 0.0;
    }
    else
    {
        weight
    }) * (1.0
        + (if reps <= 0
        {
            return 0.0;
        }
        else
        {
            reps as f64
        }) / 30.0)
}

/// Wathan 公式：从 1RM 反推"目标次数下的预估重量"（MRM）
///
/// 公式：`MRM = 1RM / (1.67 − 0.067 × target_reps)`
///
/// 【教学：实现提示】
/// 1. 边界：one_rm <= 0.0 或 target_reps <= 0 → return 0.0
/// 2. 分母：1.67 - 0.067 * target_reps as f64
///    （target_reps 取 1/2/3 时分母为正，但防御性起见仍要判边界）
/// 3. 计算：one_rm / 分母
pub fn wathan_mrm(one_rm: f64, target_reps: i64) -> f64
{
    (if one_rm <= 0.0
    {
        return 0.0;
    }
    else
    {
        one_rm
    }) / (1.67
        - 0.067
            * (if target_reps <= 0
            {
                return 0.0;
            }
            else
            {
                target_reps as f64
            }))
}

// ============================================================
// 【教学：单元测试 —— Rust 自带，不用装库】
// ============================================================
// #[cfg(test)] 表示：下面的模块只在 `cargo test` 时编译，
// 正常 `cargo build` 不带上它（不增加产物体积）。
//
// 浮点数比较技巧：
//   浮点有精度误差（0.1 + 0.2 != 0.3），不能 assert_eq!(a, b) 精确比较。
//   用 (a - b).abs() < 0.01 判断"足够接近"。
//
// 【M5 要求：写 3 个测试】
//   1. epley_1rm(60.0, 8)  ≈ 76.0   （60 × (1 + 8/30)）
//   2. wathan_mrm(100.0, 2) ≈ 65.1   （100 / (1.67 − 0.134)）
//   3. 无效输入返回 0（多测几种：weight=0、reps=0、负数）
// ============================================================
#[cfg(test)]
mod tests
{
    // 【教学：super:: 是什么？】
    // tests 是 calc 的子模块，super 指"上一层的 calc 模块"。
    // use super::* 把 calc 里的函数（epley_1rm 等）都引入测试作用域。
    use super::*;

    // 你在这里写 3 个 #[test] 函数：
    #[test]
    fn test_epley_1rm()
    {
        assert!((epley_1rm(60.0, 8) - 76.0).abs() < 0.01);
    }
    #[test]
    fn test_wathan_mrm()
    {
        assert!((wathan_mrm(100.0, 2) - 65.1).abs() < 0.01);
    }
    #[test]
    fn test_invalid_input()
    {
        assert_eq!(wathan_mrm(0.0, 2), 0.0);
        assert_eq!(wathan_mrm(100.0, 0), 0.0);
        assert_eq!(epley_1rm(0.0, 8), 0.0);
        assert_eq!(epley_1rm(60.0, 0), 0.0);
        assert_eq!(epley_1rm(-10.0, 8), 0.0);
    }
}
