-- 【需求来源】
-- 用户问题 0：plan_detail 的"杆重/体重"列在计重模式为 support（支撑）时，
-- 体重应来自一个"可编辑的通用变量"（训练时填写，记录页/计划页自动获取），
-- 而不是每行手填、也不是 localStorage 前端记忆。
--
-- ⚠️ SQLite ALTER TABLE ADD COLUMN 注意点（与 0004/0005 相同）：
--   新列必须允许 NULL 或带默认值；已有行自动填默认值 NULL。
--   Rust 侧模型用 Option<f64>（未设置 = None，界面显示"未设置"）。
--
-- 为什么不放 localStorage / 环境变量？
--   - localStorage 是浏览器端记忆，换设备/换浏览器就丢，且服务端算不了
--   - 环境变量是部署配置，不适合"用户日常维护的数据"
--   - users 表是"用户自己的属性"的归属地（display_name 同款），
--     体重是用户属性 → 放 users 表，天然数据隔离（按 user_id）
-- ============================================================

-- 用户体重（kg，可空 = 未设置；support 模式换算用）
ALTER TABLE users ADD COLUMN body_weight REAL;
